 "alias":'PRODUCT_VIEW',
 "schema": 'GOLD'
})}}

WITH view AS(
SELECT
    PRODUCT_ID AS PRODUCT_ID
    ,DBT_VALID_FROM AS VRSN_STRT_DTS
    ,COALESCE(DBT_VALID_TO , '9999-12-31 00:00:00.000') AS VRSN_END_DTS
    ,PRODUCT_NAME AS PRODUCT_NAME
    ,CATEGORY AS CATEGORY
    ,SELLING_PRICE AS SELLING_PRICE
    ,MODEL_NUMBER AS MODEL_NUMBER
    ,ABOUT_PRODUCT AS ABOUT_PRODUCT
    ,PRODUCT_SPECIFICATION AS PRODUCT_SPECIFICATION
    ,TECHNICAL_DETAILS AS TECHNICAL_DETAILS
    ,SHIPPING_WEIGHT AS SHIPPING_WEIGHT
    ,PRODUCT_DIMENSIONS AS PRODUCT_DIMENSIONS
    ,'UTC' AS TIME_ZONE                                      -- Matches dbt's default snapshot timezone (or use CURRENT_SETTING('TIMEZONE'))
    ,'SCD2_DB.SILVER.WORK_PRODUCT_TRANSFORM' AS SOURCE_SYS_NAME -- Or static label like 'SNOWFLAKE_SILVER'
    ,'{{ target.name }}' AS INSTNC_ST_NM                     -- Captures the dbt environment/target name (e.g., 'default' or 'prod')
    ,'{{ invocation_id }}' AS PROCESS_ID                     -- Unique UUID generated by dbt for each run
    ,'{{ this.name }}' AS PROCESS_NAME                       -- Evaluates to 'PRODUCT_VIEW' (or use 'product_snapshot')
    ,DBT_VALID_FROM AS INSERT_DTS                            -- Exact timestamp when this SCD2 version was inserted
    ,DBT_UPDATED_AT AS UPDATE_DTS                            -- Exact timestamp when this SCD2 record was last updated
FROM {{ref('product_snapshot')}}
)
SELECT *
FROM view